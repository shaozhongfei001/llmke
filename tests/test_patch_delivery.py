"""Overlay safety: real replace/delete, full backup, rerun and guarded restore."""
from pathlib import Path
import json
import pytest
from fixture_helpers import PROJECT
import apply_baseline_patch as patch

def fixture(tmp):
 bundle=tmp/'bundle';overlay=bundle/'overlay';overlay.mkdir(parents=True);target=tmp/'target';target.mkdir()
 (overlay/'AI_GUIDE.md').write_text('new guide');(overlay/'new.txt').write_text('new')
 (target/'AI_GUIDE.md').write_text('local original');(target/'obsolete.txt').write_text('old');(target/'unrelated.py').write_text('keep me')
 rows=[{'path':'AI_GUIDE.md','action':'REPLACE','sha256':patch.sha(overlay/'AI_GUIDE.md'),'base_sha256':'a'*64},{'path':'new.txt','action':'ADD','sha256':patch.sha(overlay/'new.txt'),'base_sha256':None},{'path':'obsolete.txt','action':'DELETE','sha256':None,'base_sha256':patch.sha(target/'obsolete.txt')}]
 (bundle/'PATCH-MANIFEST.json').write_text(json.dumps({'patch_id':'fixture-only','files':rows,'reset_prefixes':['loops/T1/evidence']}))
 return bundle,target

def test_overlay_plan_is_readonly(tmp_path):
 b,t=fixture(tmp_path);before={p.name:p.read_bytes() for p in t.iterdir()};patch.apply(b,t,False)
 assert before=={p.name:p.read_bytes() for p in t.iterdir()}

def test_overlay_backup_restore_and_unrelated_files(tmp_path):
 b,t=fixture(tmp_path);p=t/'loops/T1/evidence';p.mkdir(parents=True);(p/'new_runtime.log').write_text('prior runtime')
 backup=patch.apply(b,t,True)
 assert(t/'AI_GUIDE.md').read_text()=='new guide' and not(t/'obsolete.txt').exists() and not(p/'new_runtime.log').exists()
 assert(t/'unrelated.py').read_text()=='keep me'
 (t/'later_business.py').write_text('new independent work')
 assert patch.apply(b,t,True) is None
 patch.rollback(t,backup)
 assert(t/'AI_GUIDE.md').read_text()=='local original' and(t/'obsolete.txt').read_text()=='old' and not(t/'new.txt').exists()
 assert(p/'new_runtime.log').read_text()=='prior runtime' and(t/'later_business.py').is_file()

