def test_mid_apply_exception_restores_every_original(tmp_path,monkeypatch):
 b,t=fixture(tmp_path);original=patch.put;count={'n':0}
 def fail_once(src,dest):
  count['n']+=1
  if count['n']==2:raise OSError('synthetic apply failure')
  return original(src,dest)
 monkeypatch.setattr(patch,'put',fail_once)
 with pytest.raises(OSError):patch.apply(b,t,True)
 assert(t/'AI_GUIDE.md').read_text()=='local original'
 assert(t/'obsolete.txt').read_text()=='old' and not(t/'new.txt').exists() and not(t/patch.RECEIPT).exists()


def test_regenerated_build_cache_is_archived_then_restored(tmp_path):
 b,t=fixture(tmp_path);rel='contracts/build/generate-report.json';f=b/'overlay'/rel;f.parent.mkdir(parents=True);f.write_text('original generated report')
 m=json.loads((b/'PATCH-MANIFEST.json').read_text());m['files'].append({'path':rel,'action':'ADD','sha256':patch.sha(f),'base_sha256':None});m['regenerable_paths']=[rel];(b/'PATCH-MANIFEST.json').write_text(json.dumps(m))
 backup=patch.apply(b,t,True);(t/rel).write_text('regenerated by make verify')
 patch.rollback(t,backup)
 assert not(t/rel).exists()
 assert(backup/'regenerated-before-rollback'/rel).read_text()=='regenerated by make verify'
