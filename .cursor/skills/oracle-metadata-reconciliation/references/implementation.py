#!/usr/bin/env python3
"""
Oracle 元数据自动汇总与人工数据字典核对工具 — 工作实现
路径: ~/dev/pyws/oracle_metadata_reconciliation.py
"""

# ──────────────────────────────────────────────────────────────
# 关键经验与陷阱
# ──────────────────────────────────────────────────────────────
# 1. openpyxl 使用 wb[sheet_name] 不是 wb.get(sheet_name)
# 2. Oracle 数据库字符集 ZHS16GBK 时，历史迁移数据注释可能永久
#    损坏为 0x3f 问号字节，无法通过编码转换恢复
# 3. thick 模式需要 oracledb.init_oracle_client(lib_dir="<oracle-client-dir>")
# 4. 三个字典文件格式完全不同：
#    - 数据仓库数据ACRM相关数据字典.xlsx: 每个表一个sheet
#    - DICT_ACRM数据挖掘前期分析数据模型_V1.xlsx: 分类sheet，结构松散
#    - DICT_ACRM系统基础表字段级分析.xlsx: 单个大sheet，字段级分析明细
# 5. Excel 解析需处理合并单元格、空表名向下填充、多schema引用(OMDATA/EDWCRM)
# 6. Excel 必须 data_only=True 才能读取计算后的值
# 7. 输出 xlsx 时逐行写入，不要用空行填充

# ──────────────────────────────────────────────────────────────
# 损坏注释检测逻辑
# ──────────────────────────────────────────────────────────────
# Oracle 用 DUMP(comments, 1016) 可确认字节是否为 3f,3f,3f...
# 如果是，说明存入时已损坏，不是读取编码问题
# Python 侧检测: set(str(comment).strip()) == {"?"} and len >= 2

# ──────────────────────────────────────────────────────────────
# 字典文件解析要点
# ──────────────────────────────────────────────────────────────
# Dict1 (数据仓库数据ACRM相关数据字典.xlsx):
#   - 清单 sheet: B=序号, C=SCHEMA, D=表ID, E=表中文名
#   - 表 sheet: A=列ID, B=列ID名, C=列中文名, D=字段类型, E=是否主键, F=是否为空, G=备注
#   - 表名 = sheet 名
#
# Dict2 (DICT_ACRM数据挖掘前期分析数据模型_V1.xlsx):
#   - 各分类sheet，表名在数据行中 (Sxx_ 模式)
#   - 解析困难，返回 0 张有效表（结构过于松散）
#
# Dict3 (DICT_ACRM系统基础表字段级分析.xlsx):
#   - 字段级分析明细详情 sheet
#   - A=表序号(新表标记), B=平台名, C=字段序号, D=源系统表名(Schema.Table),
#     E=源表中文名, F=源系统字段名, H=源字段中文名, I=源系统数据类型
#   - D 列格式: "OMDATA.S01_FFHZ/OMDATA.S07_FFHZ" 需取第一个 part 的表名
#   - 新表序号出现时重置字段计数

# ──────────────────────────────────────────────────────────────
# Oracle 连接要点
# ──────────────────────────────────────────────────────────────
# - 连接信息只从环境变量读取: <db-host>:1521/<service-name>（真实值绝不入库）
# - thick 模式需 init_oracle_client 指定 <oracle-client-dir>；thin 模式留空即可
# - 外键数量可能为0 (实际项目中外键约束通常不建)
# - 表数与列数可能不一致 (212表但213张表有列，可能是空表)
